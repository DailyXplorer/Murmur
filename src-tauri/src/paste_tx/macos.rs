/// Concealment marker types declared alongside the text so that well-behaved
/// third-party clipboard managers (Maccy, Paste, ...) skip the transcript.
/// These are conventions, not a security boundary.
const CONCEALMENT_TYPES: [&str; 3] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];
const TEXT_PASTEBOARD_TYPE: &str = "public.utf8-plain-text";

pub struct ProviderIvars {
    state: Arc<Mutex<TxState>>,
    text: String,
}

define_class!(
    // SAFETY: NSObject has no subclassing requirements and the ivars are
    // plain Rust values guarded by a Mutex.
    #[unsafe(super(NSObject))]
    #[name = "MurmurPasteProvider"]
    #[ivars = ProviderIvars]
    pub struct MurmurPasteProvider;

    impl MurmurPasteProvider {
        // NSPasteboardOwner informal protocol: the pasteboard is asking for the
        // promised data — our receipt that a consumer read the clipboard.
        #[unsafe(method(pasteboard:provideDataForType:))]
        fn pasteboard_provide_data_for_type(&self, pasteboard: &NSPasteboard, data_type: &NSString) {
            let ivars = self.ivars();
            // SAFETY: NSPasteboardTypeString is a read-only framework static.
            let is_text = unsafe { data_type.isEqualToString(NSPasteboardTypeString) };
            // Only a text read counts as a receipt: a request for one of the
            // concealment marker types is a clipboard manager inspecting the
            // markers, not the paste target reading the transcript.
            if is_text {
                if let Ok(mut state) = ivars.state.lock() {
                    state.record_receipt(Instant::now());
                }
            }
            let payload = if is_text {
                NSString::from_str(&ivars.text)
            } else {
                // Concealment marker types are never handed out.
                NSString::from_str("")
            };
            let _ = pasteboard.setString_forType(&payload, data_type);
        }

        #[unsafe(method(pasteboardChangedOwner:))]
        fn pasteboard_changed_owner(&self, _pasteboard: &NSPasteboard) {
            if let Ok(mut state) = self.ivars().state.lock() {
                state.ownership_lost = true;
            }
        }
    }
);

impl MurmurPasteProvider {
    fn new(state: Arc<Mutex<TxState>>, text: String) -> Retained<Self> {
        let this = Self::alloc().set_ivars(ProviderIvars { state, text });
        unsafe { msg_send![super(this), init] }
    }
}

/// The clipboard as it was before Murmur published a transcript: every item,
/// with the data of every type it offered, so restoring it is lossless.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
struct SavedClipboard {
    items: Vec<Vec<(String, Vec<u8>)>>,
}

impl SavedClipboard {
    /// Must run on the main thread.
    fn capture(pasteboard: &NSPasteboard) -> Self {
        let mut items = Vec::new();
        for item in pasteboard
            .pasteboardItems()
            .iter()
            .flat_map(|items| items.iter())
        {
            let entries: Vec<_> = item
                .types()
                .iter()
                .filter_map(|data_type| {
                    let data = item.dataForType(&data_type)?;
                    Some((data_type.to_string(), data.to_vec()))
                })
                .collect();
            if !entries.is_empty() {
                items.push(entries);
            }
        }
        Self { items }
    }

    /// Replaces the clipboard with the saved items. Must run on the main thread.
    fn restore(&self, pasteboard: &NSPasteboard) -> bool {
        pasteboard.clearContents();
        if self.items.is_empty() {
            return true;
        }
        let items: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = self
            .items
            .iter()
            .map(|entries| {
                let item = NSPasteboardItem::new();
                for (data_type, bytes) in entries {
                    item.setData_forType(
                        &NSData::with_bytes(bytes),
                        &NSString::from_str(data_type),
                    );
                }
                ProtocolObject::from_retained(item)
            })
            .collect();
        pasteboard.writeObjects(&NSArray::from_retained_slice(&items))
    }
}

struct MacPending {
    state: Arc<Mutex<TxState>>,
    change_count: NSInteger,
    provider: Option<Retained<MurmurPasteProvider>>,
    /// ClipboardHandling::CopyToClipboard settles by materializing every
    /// promised type so the transcript outlives the provider. Otherwise Murmur
    /// puts the previous clipboard back after settlement.
    preserve_transcript: bool,
    /// The transcript, for `preserve_transcript` materialization at settle time.
    transcript: String,
    /// The user's clipboard from before the paste, restored at settlement.
    previous: SavedClipboard,
    settled: bool,
}

/// Initial reliable-paste receipt. Its asynchronous method covers only the
/// cancellable auto-submit delay; pasteboard settlement stays independent.
pub(crate) struct ReliablePasteReceipt {
    pending: Arc<Mutex<MacPending>>,
    operation: ProcessingOperation,
    release: PasteReleaseReceipt,
    auto_submit: Option<(AutoSubmitKey, FrontmostTarget)>,
}

/// The transaction currently holding the clipboard, if any. A new paste
/// settles it before publishing its own promise (see `flush_pending`).
static PENDING: Mutex<Option<Arc<Mutex<MacPending>>>> = Mutex::new(None);

/// Materializes every type promised through `declareTypes:owner:` before the
/// provider is released. Must run on the main thread.
fn materialize_promised_data(pasteboard: &NSPasteboard, transcript: &str) -> bool {
    let payload = NSString::from_str(transcript);
    let text_type = NSString::from_str(TEXT_PASTEBOARD_TYPE);
    if !pasteboard.setString_forType(&payload, &text_type) {
        return false;
    }

    let empty = NSString::from_str("");
    for marker in CONCEALMENT_TYPES {
        let marker_type = NSString::from_str(marker);
        if !pasteboard.setString_forType(&empty, &marker_type) {
            return false;
        }
    }
    true
}

fn finish_settlement(pending: &mut MacPending) {
    pending.settled = true;
    // Every promised type has been materialized, erased, or replaced by an
    // external owner, so the provider no longer needs to stay alive.
    pending.provider = None;
}

/// Settles a transaction exactly once by keeping the transcript or putting
/// the previous clipboard back. Nothing is written once someone else owns the
/// clipboard. Auto-submit happens only in the targeted event path and never
/// depends on an AppKit read callback. Must run on the main thread.
fn settle(pending: &Arc<Mutex<MacPending>>) {
    let mut p = match pending.lock() {
        Ok(p) => p,
        Err(_) => return,
    };
    if p.settled {
        return;
    }
    let (ownership_lost, injection_failed) = match p.state.lock() {
        Ok(st) => (st.ownership_lost, st.injection_failed),
        Err(_) => (true, false),
    };

    let still_ours =
        !ownership_lost && NSPasteboard::generalPasteboard().changeCount() == p.change_count;

    // If the chord never reached the target, retaining the transcript is the
    // only non-destructive outcome. The caller's clear-after-paste preference
    // applies only after a paste was actually injected.
    match decide_settlement(still_ours, p.preserve_transcript || injection_failed) {
        ClipboardSettlement::LeaveUntouched => {
            info!("[reliable-paste] clipboard changed externally; leaving it untouched");
        }
        ClipboardSettlement::KeepTranscript => {
            if NSPasteboard::generalPasteboard().changeCount() != p.change_count {
                info!("[reliable-paste] clipboard changed before materialization; leaving it untouched");
                finish_settlement(&mut p);
                return;
            }
            // Fill every declared type in place. Unlike arboard::set_text,
            // this does not clear the promise before attempting the write.
            if materialize_promised_data(&NSPasteboard::generalPasteboard(), &p.transcript) {
                info!("[reliable-paste] materialized transcript for clipboard recovery");
            } else {
                info!("[reliable-paste] clipboard changed during materialization; leaving it untouched");
            }
        }
        ClipboardSettlement::RestorePrevious => {
            let pasteboard = NSPasteboard::generalPasteboard();
            if pasteboard.changeCount() != p.change_count {
                info!("[reliable-paste] clipboard changed before restore; leaving it untouched");
                finish_settlement(&mut p);
                return;
            }
            if p.previous.restore(&pasteboard) {
                info!(
                    "[reliable-paste] restored the previous clipboard ({} items)",
                    p.previous.items.len()
                );
            } else {
                error!("[reliable-paste] failed to restore the previous clipboard");
            }
        }
    }

    finish_settlement(&mut p);
}

#[derive(Debug, PartialEq, Eq)]
enum ClipboardSettlement {
    RestorePrevious,
    KeepTranscript,
    LeaveUntouched,
}

fn decide_settlement(still_ours: bool, preserve_transcript: bool) -> ClipboardSettlement {
    if !still_ours {
        ClipboardSettlement::LeaveUntouched
    } else if preserve_transcript {
        ClipboardSettlement::KeepTranscript
    } else {
        ClipboardSettlement::RestorePrevious
    }
}

/// If a previous transaction is still holding the clipboard, settle it before
/// publishing a new promise.
fn flush_pending() {
    let previous = match PENDING.lock() {
        Ok(mut slot) => slot.take(),
        Err(_) => None,
    };
    if let Some(previous) = previous {
        settle(&previous);
    }
}

#[derive(Debug, PartialEq)]
enum PasteboardAdmission {
    Claimed,
    Cancelled,
    TargetChanged,
}

/// Rejected callbacks must not settle an older transaction or publish text.
fn claim_before_pasteboard_mutation<F>(
    operation: &ProcessingOperation,
    target_is_current: impl FnOnce() -> bool,
    mutation: F,
) -> PasteboardAdmission
where
    F: FnOnce(),
{
    if !target_is_current() {
        return PasteboardAdmission::TargetChanged;
    }
    let Some(_permit) = operation.try_enter_paste() else {
        return PasteboardAdmission::Cancelled;
    };
    mutation();
    PasteboardAdmission::Claimed
}

fn same_pending<T>(current: Option<&Arc<Mutex<T>>>, candidate: &Arc<Mutex<T>>) -> bool {
    current
        .map(|pending| Arc::ptr_eq(pending, candidate))
        .unwrap_or(false)
}

fn is_current_pending(candidate: &Arc<Mutex<MacPending>>) -> bool {
    PENDING
        .lock()
        .map(|slot| same_pending(slot.as_ref(), candidate))
        .unwrap_or(false)
}

fn spawn_waiter(pending: Arc<Mutex<MacPending>>, app_handle: AppHandle) {
    tauri::async_runtime::spawn(async move {
        let outcome = loop {
            tokio::time::sleep(Duration::from_millis(15)).await;
            let (decision, state_snapshot) = {
                let p = match pending.lock() {
                    Ok(p) => p,
                    Err(_) => return,
                };
                if p.settled {
                    // A newer paste settled this transaction already.
                    return;
                }
                let result = match p.state.lock() {
                    Ok(st) => {
                        let now = Instant::now();
                        let snapshot = (st.ownership_lost, st.injection_failed, st.logged_receipt);
                        (evaluate(&st, now), snapshot)
                    }
                    Err(_) => return,
                };
                result
            };
            if let WaitDecision::Finish = decision {
                break state_snapshot;
            }
        };

        let (ownership_lost, injection_failed, read_observed) = outcome;
        if ownership_lost {
            info!("[reliable-paste] settling: clipboard ownership lost");
        } else if injection_failed {
            info!("[reliable-paste] settling early after chord injection failure");
        } else if read_observed {
            info!("[reliable-paste] settling after bounded lifetime; read observed");
        } else {
            info!("[reliable-paste] settling after bounded lifetime; no read observed");
        }

        let pending_for_finish = pending.clone();
        let _ = app_handle.run_on_main_thread(move || {
            settle(&pending_for_finish);
            if let Ok(mut slot) = PENDING.lock() {
                if same_pending(slot.as_ref(), &pending) {
                    *slot = None;
                }
            }
        });
    });
}

impl ReliablePasteReceipt {
    /// Keeps the pipeline cancellable until the delayed auto-submit has either
    /// run or been suppressed. It intentionally does not wait for settlement.
    pub(crate) async fn complete_auto_submit(self, app_handle: AppHandle) -> Result<(), String> {
        self.release.wait().await?;
        let Some((auto_submit_key, target)) = self.auto_submit else {
            return Ok(());
        };
        if self.operation.cancellation_requested() {
            return Ok(());
        }

        tokio::select! {
            _ = tokio::time::sleep(Duration::from_millis(50)) => {}
            _ = self.operation.cancelled() => return Ok(()),
        }
        if self.operation.cancellation_requested() {
            return Ok(());
        }

        let (sender, mut receiver) = oneshot::channel();
        let pending = self.pending.clone();
        let operation = self.operation.clone();
        app_handle
            .run_on_main_thread(move || {
                if !operation.cancellation_requested() {
                    // A newer paste may have replaced this transaction while
                    // the delay elapsed. Focus identity alone cannot detect
                    // that when both pastes target the same application.
                    if !is_current_pending(&pending) {
                        info!("[reliable-paste] skipping auto-submit for superseded transaction");
                    } else if let Err(error) =
                        send_return_if_target_unchanged(auto_submit_key, Some(target)).map(|_| ())
                    {
                        error!("[reliable-paste] paste succeeded, but auto-submit failed: {error}");
                    }
                }
                let _ = sender.send(());
            })
            .map_err(|error| format!("[reliable-paste] failed to queue auto-submit: {error}"))?;

        tokio::select! {
            result = &mut receiver => result
                .map_err(|_| "[reliable-paste] queued auto-submit was dropped".to_string()),
            _ = self.operation.cancelled() => Ok(()),
        }
    }
}

pub(super) fn run(
    text: &str,
    app_handle: &AppHandle,
    auto_submit: bool,
    auto_submit_key: AutoSubmitKey,
    clipboard_handling: ClipboardHandling,
    operation: ProcessingOperation,
) -> ReliablePasteOutcome {
    let Some(target) = frontmost_target() else {
        return ReliablePasteOutcome::Skipped;
    };

    let state = Arc::new(Mutex::new(TxState::new()));
    let provider = MurmurPasteProvider::new(state.clone(), text.to_string());
    let pasteboard = NSPasteboard::generalPasteboard();

    let mut types: Vec<Retained<NSString>> = Vec::with_capacity(1 + CONCEALMENT_TYPES.len());
    types.push(NSString::from_str(TEXT_PASTEBOARD_TYPE));
    for t in CONCEALMENT_TYPES {
        types.push(NSString::from_str(t));
    }
    let types = NSArray::from_retained_slice(&types);

    match claim_before_pasteboard_mutation(
        &operation,
        || frontmost_target().as_ref() == Some(&target),
        flush_pending,
    ) {
        PasteboardAdmission::Claimed => {}
        PasteboardAdmission::Cancelled => return ReliablePasteOutcome::Cancelled,
        PasteboardAdmission::TargetChanged => return ReliablePasteOutcome::Skipped,
    }

    // After flush_pending, so an earlier Murmur paste has already put the
    // user's own clipboard back and that is what gets saved.
    let previous = if clipboard_handling == ClipboardHandling::CopyToClipboard {
        SavedClipboard::default()
    } else {
        SavedClipboard::capture(&pasteboard)
    };

    // declareTypes:owner: clears the pasteboard and puts our promise on it;
    // the return value is the new changeCount.
    let change_count: NSInteger =
        unsafe { msg_send![&*pasteboard, declareTypes: &*types, owner: &*provider] };
    if change_count <= 0 {
        error!("[reliable-paste] declareTypes:owner: failed after output claim");
        return ReliablePasteOutcome::Skipped;
    }
    info!("[reliable-paste] published transcript as lazy promise (changeCount {change_count})");

    // The target may read while Command is still held.
    if let Ok(mut st) = state.lock() {
        st.injected_at = Some(Instant::now());
    }
    let release = match send_paste_if_target_unchanged(Some(target.clone()), app_handle) {
        Ok(Some(receipt)) => {
            info!("[reliable-paste] Cmd+V sent");
            Some(receipt)
        }
        Ok(None) => {
            if let Ok(mut st) = state.lock() {
                st.injection_failed = true;
            }
            info!("[reliable-paste] target changed before Cmd+V; paste skipped");
            None
        }
        Err(e) => {
            // Keep the transaction alive long enough to replace the promise
            // with plain transcript text. A failed chord never authorizes
            // restoration of the previous clipboard.
            if let Ok(mut st) = state.lock() {
                st.injection_failed = true;
            }
            error!("[reliable-paste] failed to send paste chord: {e}");
            None
        }
    };

    let pending = Arc::new(Mutex::new(MacPending {
        state,
        change_count,
        provider: Some(provider),
        preserve_transcript: clipboard_handling == ClipboardHandling::CopyToClipboard,
        transcript: text.to_string(),
        previous,
        settled: false,
    }));
    if let Ok(mut slot) = PENDING.lock() {
        *slot = Some(pending.clone());
    }
    spawn_waiter(pending.clone(), app_handle.clone());

    if let Some(release) = release {
        ReliablePasteOutcome::Injected(ReliablePasteReceipt {
            pending,
            operation,
            release,
            auto_submit: auto_submit.then_some((auto_submit_key, target)),
        })
    } else {
        ReliablePasteOutcome::Skipped
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::operation::OperationId;

    #[test]
    fn restores_the_previous_clipboard_only_while_murmur_still_owns_it() {
        assert_eq!(
            decide_settlement(true, false),
            ClipboardSettlement::RestorePrevious
        );
        assert_eq!(
            decide_settlement(false, false),
            ClipboardSettlement::LeaveUntouched
        );
    }

    #[test]
    fn saved_clipboard_round_trips_every_item_and_type() {
        // A private pasteboard, so the test never touches the user's clipboard.
        let pasteboard = NSPasteboard::pasteboardWithUniqueName();
        let saved = SavedClipboard {
            items: vec![
                vec![
                    ("public.utf8-plain-text".to_string(), b"first".to_vec()),
                    ("public.html".to_string(), b"<b>first</b>".to_vec()),
                ],
                vec![("com.example.custom".to_string(), vec![0, 1, 2, 255])],
            ],
        };
        assert!(saved.restore(&pasteboard));

        pasteboard.clearContents();
        assert!(materialize_promised_data(&pasteboard, "transcript"));
        assert!(saved.restore(&pasteboard));

        let restored = SavedClipboard::capture(&pasteboard);
        release(&pasteboard);
        assert_eq!(restored.items.len(), 2);
        for (saved_item, restored_item) in saved.items.iter().zip(&restored.items) {
            for entry in saved_item {
                assert!(restored_item.contains(entry), "missing {:?}", entry.0);
            }
        }
    }

    #[test]
    fn empty_previous_clipboard_restores_to_empty() {
        let pasteboard = NSPasteboard::pasteboardWithUniqueName();
        pasteboard.clearContents();
        assert!(materialize_promised_data(&pasteboard, "transcript"));

        assert!(SavedClipboard::default().restore(&pasteboard));

        let restored = SavedClipboard::capture(&pasteboard);
        release(&pasteboard);
        assert_eq!(restored, SavedClipboard::default());
    }

    fn release(pasteboard: &NSPasteboard) {
        let _: () = unsafe { msg_send![pasteboard, releaseGlobally] };
    }

    #[test]
    fn copy_to_clipboard_always_keeps_transcript() {
        assert_eq!(
            decide_settlement(true, true),
            ClipboardSettlement::KeepTranscript
        );
    }

    #[test]
    fn failed_injection_keeps_transcript_for_recovery() {
        let preserve_transcript = false;
        let injection_failed = true;
        assert_eq!(
            decide_settlement(true, preserve_transcript || injection_failed),
            ClipboardSettlement::KeepTranscript
        );
    }

    #[test]
    fn cancellation_before_queued_callback_leaves_live_pending_unsettled() {
        let operation = ProcessingOperation::new(OperationId(7));
        let pending = Arc::new(Mutex::new(Some("live-pr64-transaction")));
        assert!(operation.cancel());

        let pending_for_mutation = pending.clone();
        assert_eq!(
            claim_before_pasteboard_mutation(
                &operation,
                || true,
                move || {
                    pending_for_mutation.lock().unwrap().take();
                }
            ),
            PasteboardAdmission::Cancelled
        );
        assert_eq!(*pending.lock().unwrap(), Some("live-pr64-transaction"));
    }

    #[test]
    fn target_changed_before_publication_leaves_clipboard_and_pending_untouched() {
        let operation = ProcessingOperation::new(OperationId(8));
        let mut pending = Some("previous-transaction");
        let mut clipboard = "original-clipboard";
        let captured_target = "application-a";
        let current_target = "application-b";

        let admission = claim_before_pasteboard_mutation(
            &operation,
            || current_target == captured_target,
            || {
                pending.take();
                clipboard = "transcript";
            },
        );

        assert_eq!(admission, PasteboardAdmission::TargetChanged);
        assert_eq!(pending, Some("previous-transaction"));
        assert_eq!(clipboard, "original-clipboard");
        assert!(operation.try_enter_paste().is_some());
    }

    #[test]
    fn auto_submit_guard_accepts_only_the_current_transaction() {
        fn pending() -> Arc<Mutex<()>> {
            Arc::new(Mutex::new(()))
        }

        let current = pending();
        let superseded = pending();

        assert!(same_pending(Some(&current), &current));
        assert!(!same_pending(Some(&current), &superseded));
        assert!(!same_pending(None, &current));
    }

    #[test]
    fn reliable_paste_waiter_has_no_blocking_thread_sleep() {
        let forbidden = ["thread", "::sleep"].concat();
        assert!(!include_str!("macos.rs").contains(&forbidden));
    }
}
